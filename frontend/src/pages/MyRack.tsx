import React, { useState, useEffect } from 'react';
import { MoreHorizontal } from 'lucide-react';
import { collection, onSnapshot } from 'firebase/firestore';
// Make sure you have exported 'db' from your firebase initialization file
import { db } from '../services/firebase'; 

// Defines the structure expected from your Firebase database
interface Product {
  id: string;
  name: string;
  brand: string;
  category: string;
  ingredients: string[];
  instructions: string;
  imageUrl?: string;
  status: "using" | "planning" | "stopped";
  createdAt: string;
  // UI-specific fallbacks
  infoStatus?: string;
  infoLevel?: number;
  routine?: string[];
  initials?: string;
}

export default function MyRack() {
  const [products, setProducts] = useState<Product[]>([]);

  useEffect(() => {
    // Listen for real-time updates from the 'products' collection in Firestore
    const unsubscribe = onSnapshot(collection(db, 'products'), (snapshot) => {
      const rackData = snapshot.docs.map(doc => {
        const data = doc.data();
        return {
          id: doc.id,
          name: data.name || "Unknown Product",
          brand: data.brand || "Unknown Brand",
          category: data.category || "Uncategorized",
          ingredients: data.ingredients || [],
          instructions: data.instructions || "",
          imageUrl: data.imageUrl || null,
          status: data.status || "planning",
          createdAt: data.createdAt || new Date().toISOString(),
          
          // Provide visual fallbacks for fields that might not be generated by the AI yet
          infoStatus: data.infoStatus || (data.ingredients?.length > 0 ? "Complete" : "Partial"),
          infoLevel: data.infoLevel || (data.ingredients?.length > 0 ? 3 : 1),
          routine: data.routine || [],
          initials: data.name ? data.name.split(' ').map((n: string) => n[0]).join('').substring(0, 2).toUpperCase() : "??"
        } as Product;
      });
      setProducts(rackData);
    });

    // Cleanup the listener when the component unmounts
    return () => unsubscribe();
  }, []);

  return (
    <div className="flex flex-col font-sans text-gray-800 -mx-4 -mt-4 bg-[#F8F5F1] min-h-screen">
      <header className="px-6 pt-10 pb-4">
        <h1 className="text-4xl font-bold font-serif text-[#3A2D2A] mb-1">My Rack</h1>
        <p className="text-gray-500">{products.length} saved products</p>
      </header>

      <div className="px-6 pb-8">
        <div className="flex flex-col gap-4">
          {products.map((product) => (
            <div key={product.id} className="bg-white rounded-2xl p-4 flex gap-4 items-center shadow-sm border border-gray-50">
              <div className="w-16 h-16 rounded-xl bg-[#EBE3D9] flex-shrink-0 flex items-center justify-center overflow-hidden">
                {product.imageUrl ? (
                  <img src={product.imageUrl} alt={product.name} className="w-full h-full object-cover" />
                ) : (
                  <span className="font-serif font-bold text-[#4A3B39] text-xl">{product.initials}</span>
                )}
              </div>

              <div className="flex-1 min-w-0">
                <div className="flex justify-between items-start">
                  <h3 className="font-bold text-[#3A2D2A] truncate pr-2">{product.name}</h3>
                  <button className="text-gray-400 hover:text-gray-600">
                    <MoreHorizontal size={20} />
                  </button>
                </div>
                <p className="text-sm text-gray-500 mb-2 truncate">
                  {product.brand} · {product.category}
                </p>
                
                <div className="flex items-center gap-2 mb-2">
                  <div className="flex gap-1">
                    {[1, 2, 3].map((level) => (
                      <div key={level} className={`h-1.5 w-4 rounded-full ${level <= (product.infoLevel || 0) ? 'bg-[#4A3B39]' : 'bg-[#EBE3D9]'}`} />
                    ))}
                  </div>
                  <span className="text-xs font-medium text-[#4A3B39]">Information: {product.infoStatus}</span>
                </div>

                <div className="flex gap-2">
                  {product.routine && product.routine.map((time) => (
                    <span key={time} className="px-3 py-0.5 rounded-full bg-[#F5EFE6] text-xs font-semibold text-[#4A3B39]">
                      {time}
                    </span>
                  ))}
                </div>
              </div>
            </div>
          ))}
          
          {products.length === 0 && (
            <div className="text-center py-10 text-gray-500">
              No products found. Scan a label from the Home page to add one!
            </div>
          )}
        </div>
      </div>
    </div>
  );
}